import SwiftUI
import AppKit
import Observation

struct ToolsClipboardItem: Identifiable {
    enum Kind { case text(String), image(Data), files([URL]) }
    let id = UUID()
    var kind: Kind
    var date = Date()
    var pinned = false

    var searchText: String {
        switch kind {
        case .text(let s): s
        case .image: "image"
        case .files(let u): u.map(\.lastPathComponent).joined(separator: " ")
        }
    }
}

private struct ToolsClipboardPin: Codable {
    var text: String?
    var files: [String]?
}

/// Records what you copy. Off by default; history lives in memory only (pinned text/files are saved).
@Observable
@MainActor
final class ToolsClipboard {
    static let shared = ToolsClipboard()
    private static let enabledKey = "mm.tools.clipboard.enabled"
    static let menuBarKey = "mm.tools.clipboard.menuBar"
    private static let limit = 50
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
    ]

    private(set) var items: [ToolsClipboardItem] = []
    private(set) var copiedID: UUID?

    var isEnabled: Bool {
        didSet {
            UserDefaults.standard.set(isEnabled, forKey: Self.enabledKey)
            isEnabled ? begin() : halt()
            ToolsClipboardMenuBar.shared.update()
        }
    }

    /// Explicit user choice for the menu bar icon; nil = follow `isEnabled`.
    private(set) var menuBarExplicit: Bool?

    /// Separate menu bar icon with the history popover. Defaults to on while recording is on.
    var showInMenuBar: Bool {
        get { menuBarExplicit ?? isEnabled }
        set {
            menuBarExplicit = newValue
            UserDefaults.standard.set(newValue, forKey: Self.menuBarKey)
            ToolsClipboardMenuBar.shared.update()
        }
    }

    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount

    private init() {
        isEnabled = UserDefaults.standard.bool(forKey: Self.enabledKey)
        menuBarExplicit = UserDefaults.standard.object(forKey: Self.menuBarKey) as? Bool
        loadPins()
    }

    /// Call at app launch; honours the saved enable toggle. Idempotent.
    func start() {
        if isEnabled { begin() }
    }

    func stop() { halt() }

    private func begin() {
        guard timer == nil else { return }
        lastChange = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        t.tolerance = 0.1
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func halt() {
        timer?.invalidate()
        timer = nil
    }

    // MARK: Polling

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            add(.files(urls)); return
        }
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            add(.text(s)); return
        }
        if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff), data.count < 30_000_000 {
            add(.image(data))
        }
    }

    private func add(_ kind: ToolsClipboardItem.Kind) {
        // Move duplicates to the top instead of repeating them.
        if let i = items.firstIndex(where: { Self.same($0.kind, kind) }) {
            var it = items.remove(at: i)
            it.date = Date()
            items.insert(it, at: 0)
        } else {
            items.insert(ToolsClipboardItem(kind: kind), at: 0)
        }
        trim()
    }

    private static func same(_ a: ToolsClipboardItem.Kind, _ b: ToolsClipboardItem.Kind) -> Bool {
        switch (a, b) {
        case (.text(let x), .text(let y)): return x == y
        case (.files(let x), .files(let y)): return x == y
        case (.image(let x), .image(let y)): return x.count == y.count && x == y
        default: return false
        }
    }

    private func trim() {
        var unpinned = 0
        items = items.filter { item in
            if item.pinned { return true }
            unpinned += 1
            return unpinned <= Self.limit
        }
    }

    // MARK: Actions

    func copyBack(_ item: ToolsClipboardItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text(let s): pb.setString(s, forType: .string)
        case .image(let d):
            if let img = NSImage(data: d) { pb.writeObjects([img]) } else { pb.setData(d, forType: .png) }
        case .files(let urls): pb.writeObjects(urls as [NSURL])
        }
        lastChange = pb.changeCount
        copiedID = item.id
        Task {
            try? await Task.sleep(nanoseconds: 1_200_000_000)
            if copiedID == item.id { copiedID = nil }
        }
    }

    func togglePin(_ item: ToolsClipboardItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
        savePins()
    }

    func remove(_ item: ToolsClipboardItem) {
        items.removeAll { $0.id == item.id }
        savePins()
    }

    func clearUnpinned() {
        items.removeAll { !$0.pinned }
    }

    // MARK: Persistence of pins

    private func savePins() {
        let pins: [ToolsClipboardPin] = items.filter(\.pinned).compactMap { it in
            switch it.kind {
            case .text(let s): ToolsClipboardPin(text: s, files: nil)
            case .files(let u): ToolsClipboardPin(text: nil, files: u.map(\.path))
            case .image: nil
            }
        }
        Store.save(pins, to: "clipboard-pins.json")
    }

    private func loadPins() {
        let pins = Store.load([ToolsClipboardPin].self, from: "clipboard-pins.json") ?? []
        items = pins.compactMap { p in
            if let t = p.text { return ToolsClipboardItem(kind: .text(t), pinned: true) }
            if let f = p.files { return ToolsClipboardItem(kind: .files(f.map { URL(fileURLWithPath: $0) }), pinned: true) }
            return nil
        }
    }
}

// MARK: - View

struct ToolsClipboardView: View {
    private let clip = ToolsClipboard.shared
    @State private var query = ""

    private var filtered: [ToolsClipboardItem] {
        let q = query.trimmingCharacters(in: .whitespaces)
        let all = clip.items
        let list = q.isEmpty ? all : all.filter { $0.searchText.localizedCaseInsensitiveContains(q) }
        return list.filter(\.pinned) + list.filter { !$0.pinned }
    }

    var body: some View {
        VStack(spacing: 0) {
            HStack(spacing: 12) {
                Toggle("Record clipboard", isOn: Binding(get: { clip.isEnabled }, set: { clip.isEnabled = $0 }))
                    .toggleStyle(.switch)
                Toggle("Show in menu bar", isOn: Binding(get: { clip.showInMenuBar }, set: { clip.showInMenuBar = $0 }))
                    .toggleStyle(.switch)
                Spacer()
                HStack {
                    Image(systemName: "magnifyingglass").foregroundStyle(.secondary)
                    TextField("Search", text: $query).textFieldStyle(.plain)
                }
                .padding(.horizontal, 10).padding(.vertical, 6)
                .background(.quaternary.opacity(0.5), in: RoundedRectangle(cornerRadius: 8))
                .frame(maxWidth: 200)
                Button("Clear") { clip.clearUnpinned() }.disabled(clip.items.allSatisfy(\.pinned))
            }
            .padding(Theme.pagePadding).padding(.bottom, -8)

            if !clip.isEnabled && clip.items.isEmpty {
                ToolsEmptyHint(symbol: "doc.on.clipboard",
                               text: "Turn on recording to keep your last 50 copied items.\nPasswords from password managers are never recorded, and history is kept in memory only.")
                Spacer()
            } else if filtered.isEmpty {
                ToolsEmptyHint(symbol: "magnifyingglass", text: clip.items.isEmpty ? "Copy something to see it here." : "No matches.")
                Spacer()
            } else {
                ScrollView {
                    LazyVStack(spacing: 8) {
                        ForEach(filtered) { item in ToolsClipboardRow(item: item) }
                    }
                    .padding(.horizontal, Theme.pagePadding).padding(.vertical, 12)
                }
            }
        }
    }
}

private struct ToolsClipboardRow: View {
    let item: ToolsClipboardItem
    private let clip = ToolsClipboard.shared
    @State private var hover = false

    var body: some View {
        HStack(spacing: 12) {
            preview
            Spacer(minLength: 8)
            if clip.copiedID == item.id {
                StatusPill(text: "Copied", color: .green)
            } else {
                Text(ToolsFormat.relative(item.date)).font(.caption).foregroundStyle(.tertiary)
            }
            Button { clip.togglePin(item) } label: {
                Image(systemName: item.pinned ? "pin.fill" : "pin")
                    .foregroundStyle(item.pinned ? Color.orange : Color.secondary)
            }
            .buttonStyle(.plain).help(item.pinned ? "Unpin" : "Pin")
            Button { clip.remove(item) } label: { Image(systemName: "xmark.circle.fill").foregroundStyle(.tertiary) }
                .buttonStyle(.plain).help("Remove")
        }
        .padding(10)
        .background(RoundedRectangle(cornerRadius: 10, style: .continuous).fill(.quaternary.opacity(hover ? 0.7 : 0.35)))
        .contentShape(Rectangle())
        .onHover { hover = $0 }
        .onTapGesture { clip.copyBack(item) }
    }

    @ViewBuilder
    private var preview: some View {
        switch item.kind {
        case .text(let s):
            HStack(spacing: 10) {
                Image(systemName: "text.alignleft").foregroundStyle(.secondary).frame(width: 22)
                Text(s.trimmingCharacters(in: .whitespacesAndNewlines)).lineLimit(3).font(.callout)
                    .frame(maxWidth: .infinity, alignment: .leading)
            }
        case .image(let d):
            HStack(spacing: 10) {
                if let img = NSImage(data: d) {
                    Image(nsImage: img).resizable().scaledToFit().frame(width: 54, height: 40)
                        .clipShape(RoundedRectangle(cornerRadius: 5))
                }
                Text("Image").font(.callout).foregroundStyle(.secondary)
            }
        case .files(let urls):
            HStack(spacing: 10) {
                Image(nsImage: NSWorkspace.shared.icon(forFile: urls.first?.path ?? "")).resizable().frame(width: 28, height: 28)
                VStack(alignment: .leading, spacing: 0) {
                    Text(urls.first?.lastPathComponent ?? "File").font(.callout).lineLimit(1)
                    if urls.count > 1 { Text("+ \(urls.count - 1) more").font(.caption).foregroundStyle(.secondary) }
                }
            }
        }
    }
}
