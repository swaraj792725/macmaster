/// Land/sea bitmask for the world map: 360 x 180 cells of 1 degree, row 0 = 90N..89N, column 0 = 180W..179W.
///
/// The outlines are original, hand-simplified coastlines (public geographic facts, no third-party data),
/// rasterised once at development time and stored as packed bits (MSB first, row-major, base64).
/// A cell is land when at least a quarter of it is covered, so coasts are slightly generous.
enum ClockLandMask {
    static let cols = 360, rows = 180

    static let bits: [UInt8] = {
        let data = Data(base64Encoded: packed, options: .ignoreUnknownCharacters) ?? Data()
        return data.count == cols * rows / 8 ? [UInt8](data) : [UInt8](repeating: 0, count: cols * rows / 8)
    }()

    static func cell(row: Int, col: Int) -> Bool {
        guard row >= 0, row < rows, col >= 0, col < cols else { return false }
        let i = row * cols + col
        return bits[i >> 3] & (0x80 >> UInt8(i & 7)) != 0
    }

    static func isLand(lat: Double, lon: Double) -> Bool {
        let col = min(cols - 1, max(0, Int((lon + 180).rounded(.down))))
        let row = min(rows - 1, max(0, Int((90 - lat).rounded(.down))))
        return cell(row: row, col: col)
    }

    /// Dot centres for a dotted map covering `latTop` down to `latBottom` (whole degrees). Each dot stands for a
    /// `stride` x `stride` block and is kept when at least `minimum` of the block is land.
    static func dots(stride: Int, latTop: Int, latBottom: Int, minimum: Double = 0.3) -> [(lat: Double, lon: Double)] {
        let s = max(1, stride)
        var out: [(lat: Double, lon: Double)] = []
        let firstRow = 90 - latTop, lastRow = 90 - latBottom
        var r = firstRow
        while r + s <= lastRow {
            var c = 0
            while c + s <= cols {
                var n = 0
                for dr in 0..<s { for dc in 0..<s where cell(row: r + dr, col: c + dc) { n += 1 } }
                if Double(n) / Double(s * s) >= minimum {
                    out.append((lat: 90 - Double(r) - Double(s) / 2, lon: Double(c) + Double(s) / 2 - 180))
                }
                c += s
            }
            r += s
        }
        return out
    }

